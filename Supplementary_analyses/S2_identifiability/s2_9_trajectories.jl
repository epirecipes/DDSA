# Supplement S2: fitted trajectories of map–Poisson, ODE–Poisson, infection-only DDSA and full-data DDSA on data from the
# whole outbreak, at N = 99, 1,000 and 10,000.
#   map–Poisson          discrete map with a NegBin DPH infectious period, Poisson daily counts    (ladder model 2)
#   ODE–Poisson          continuous Erlang-r ODE (the NegBin DPH's continuous analogue), Poisson daily counts (ladder
#                        model 4, with r = 1..40 and no constraint μ > r; see s2_traj_data.jl)
#   infection-only DDSA  discrete map, Multinomial infection days + Binomial(N, τ) final size         (ladder model 1)
#   full-data DDSA       infection-only DDSA plus the recovery intervals (Scenario A)                  (ladder model 6)
# The first three are numerical grid posteriors from s2_8_grid_poisson.jl (see Fits). Given the expected daily infections,
# Poisson counts conditional on their total are the Multinomial of the DDSA infection-time term, and their total is
# Poisson(Nτ) where DDSA has Binomial(N, τ). The four models therefore add one source of information at a time: the count
# of individuals never infected (map–Poisson → infection-only DDSA), then the recovery intervals (→ full-data DDSA).
# One figure per N: expected new infections per day and number infectious, posterior median and 95% CrI, with the true
# mean-field trajectory and the realised data. A fit that did not converge (R̂ > 1.01) is drawn as the median trajectory of
# each chain, with no pooled band, and summarised chain by chain in the text output: its chains sit in different regions,
# so pooled summaries would not be posterior summaries.
# Data. Generated by s2_traj_data.jl (shared with s2_8_grid_poisson.jl): N = 99, the ladder data of s2_model.jl; N = 1,000
# and 10,000, the attack-rate sweep generator of s2_4_tau_sweep_mcmc.jl at R0 = 3.16, plus recovery intervals.
# Conventions. N is the whole population, including the initial infectives (supplement S2 notation). The generator and all
# three models start the map or ODE at S_0 = 1 − ρ, I_0 = ρ (fractions of N); the expected daily infections N(S_{k−1} − S_k)
# sum to Nτ, and the data and full-data DDSA use K ~ Binomial(N, τ). ρ = 0.01 at N = 99 (ρN = 0.99, as in the ladder data)
# and 1/N otherwise; the line list holds one recovery interval for the initial infective and one for each case.
# Fits. Priors as the ladder with R0 ~ U(0.5, 20): ρ ~ Beta(1, N − 1) is estimated in all four models, and r is summed out
# (1..10 for the map, 1..40 for the ODE). Full-data DDSA is fitted here with NUTS as in s2_2 (4 chains × 4,000 draws, starts
# from the prior), with the same settings at all three N. The other three models are not sampled here: without recovery
# intervals, NUTS did not reach R̂ ≤ 1.01 at N ≥ 1,000 (NegBin count models in an earlier version of this script: map R̂
# 1.03 at N = 1,000 and 1.21 at 10,000, ODE 1.02 and 2.47; map–Poisson in s2_4: 1.27 at N = 1,000), so their draws are the
# 4,000 independent draws from the numerical grid posteriors of s2_8_grid_poisson.jl (same data and priors; run it first).
# Reference trajectories. "True mean-field trajectory": the generating map at the true parameters (expected new infections
# N(S_{k−1} − S_k) and number infectious N·I_k). The data are not a stochastic epidemic: K ~ Binomial(N, τ), the infection
# days ~ Multinomial(K, f), and the recovery intervals are drawn independently of the infection days. The realised series are
# the observed daily counts and the number infectious in the line list (the first interval paired with the initial infective,
# the others with the cases in day order; a case infected in step k is infectious in steps k, …, k + δ − 1, as in the map).
# The bands show posterior parameter uncertainty only, so they need not cover the realised series.
# Usage (from the supplementary folder, after s2_8_grid_poisson.jl):
#   julia --project=@. -t 4 S2_identifiability/s2_9_trajectories.jl
#   TRAJ_N=99,1000,10000 (default) selects N; REFIT=1 refits even if the chains exist.
# Reads chains/grid_{map,ode}_poisson_N{N}.jls and chains/grid_infonly_N{N}.jls (s2_8_grid_poisson.jl). Outputs: figs/s2_fig_trajectories_N{N}.pdf/.png,
# out/s2_9_trajectories_N{N}.txt, chains/traj_N{N}_rung6.jls
ENV["GKSwstype"] = "100"
include(joinpath(@__DIR__, "s2_model.jl"))
include(joinpath(@__DIR__, "s2_traj_data.jl"))   # DATA99, set_data!, truth_SI, R_ODE, rsupport
using Serialization, Plots
gr()
R0_HI[] = 20.0
const NS    = parse.(Int, split(get(ENV, "TRAJ_N", "99,1000,10000"), ","))
const REFIT = get(ENV, "REFIT", "") == "1"
const NDRAW = 1000                       # posterior draws used for the trajectory bands

const MODELS = ((2, "Map–Poisson",         :discrete, :pois,    false, "#eb6834"),
                (4, "ODE–Poisson",         :ode,      :pois,    false, "#2a78d6"),
                (1, "Infection-only DDSA", :discrete, :multbin, false, "#eda100"),
                (6, "Full-data DDSA",      :discrete, :multbin, true,  "#1baf7a"))
# drawn from the numerical grid posteriors of s2_8_grid_poisson.jl, not sampled here
const GRID = Dict(2 => "grid_map_poisson", 4 => "grid_ode_poisson", 1 => "grid_infonly")

# The trajectory functions (glct_traj, map_traj, ode_traj, linelist_prev) are in s2_traj_data.jl.

# ---------------------------------------------------------------- fits
const SAMPLER = NUTS(1000, 0.8; max_depth = 12, Δ_max = 1000.0)
function get_chain(N_s, rung, model)
    f = joinpath(CHAINS, "traj_N$(N_s)_rung$rung.jls")
    (isfile(f) && !REFIT) && return deserialize(f), nothing
    Random.seed!(1234)
    t = @elapsed ch = sample(model, SAMPLER, MCMCThreads(), 4000, 4; progress = false,
                             chain_type = MCMCChains.Chains, initial_params = fill(InitFromPrior(), 4))
    serialize(f, ch)
    return ch, t
end

bands(M) = ([quantile(M[t, :], 0.025) for t in axes(M, 1)], [median(M[t, :]) for t in axes(M, 1)],
            [quantile(M[t, :], 0.975) for t in axes(M, 1)])
fmt(n) = n >= 1000 ? replace(string(n), r"(\d)(?=(\d{3})+$)" => s"\1,") : string(n)

for N_s in NS
    out = open(joinpath(RES, "s2_9_trajectories_N$(N_s).txt"), "w")
    say(x) = (println(x); println(out, x); flush(out))
    β_s, ρ_s = set_data!(N_s)
    T = nsteps
    inc_true, prev_true = glct_traj(dph_nom.S, dph_nom.α, β_s, ρ_s, T)
    prev_obs = linelist_prev(th, delta, T)
    say("== N=$(N_s) (whole population, incl. ρN=$(round(ρ_s * N_s, digits=2)) initial infectives): K=$K (K/N=$(round(K/N, digits=3))), T=$T d, " *
        "$(length(delta)) recovery intervals (mean $(round(mean(delta), digits=2)) d, min $(minimum(delta))); ρ estimated, ρ ~ Beta(1, N − 1)")
    say("   truth: R0=$(round(β_s * EW, digits=3)), mean IP E[W]=$(round(EW, digits=3)) d, ρ=$(round(ρ_s, sigdigits=3)); " *
        "expected incidence peak $(round(maximum(inc_true), digits=1)) on step $(argmax(inc_true)); number infectious peak $(round(maximum(prev_true), digits=1)) on step $(argmax(prev_true) - 1)")
    say("   realised: observed incidence peak $(maximum(th)) on step $(argmax(th)); line-list number infectious peak $(maximum(prev_obs)) on step $(argmax(prev_obs) - 1)")
    res = []
    for (rung, name, map, obs, recov, col) in MODELS
        grid = haskey(GRID, rung)
        if grid
            # independent draws from the grid posterior (s2_8_grid_poisson.jl), r drawn jointly with the rest; thinned for the bands
            f = joinpath(CHAINS, "$(GRID[rung])_N$(N_s).jls")
            isfile(f) || error("$f not found: run s2_8_grid_poisson.jl with GRID_N=$(N_s) first")
            g = deserialize(f)
            (haskey(g, :th) && g.K == K && g.th == th) || error("$f was not computed on these data: rerun s2_8_grid_poisson.jl with GRID_N=$(N_s)")
            thin = max(1, div(length(g.R0), NDRAW))
            R0, ip, ρv, rd = g.R0[1:thin:end], g.mean_ip[1:thin:end], g.ρ[1:thin:end], g.r[1:thin:end]
            nch = 1; cid = ones(Int, length(rd))
        else
            model = ladder(map, obs, recov)
            ch, t = get_chain(N_s, rung, model)
            # thinned draws for the bands; r is drawn from its conditional posterior given each draw
            thin = max(1, div(size(ch, 1) * size(ch, 3), NDRAW))
            sub = ch[1:thin:end, :, :]
            Random.seed!(7)
            rd = vec([sample_index(l) for l in returned(model, sub)])
            R0, ip, ρv = vec(sub[:R0]), vec(sub[:mean_ip]), vec(sub[:ρ])
            nch = size(sub, 3); cid = repeat(1:nch, inner = size(sub, 1))   # chain of each draw (vec runs chain by chain)
        end
        inc = zeros(T, length(rd)); prev = zeros(T + 1, length(rd))
        for j in eachindex(rd)
            inc[:, j], prev[:, j] = map === :discrete ? map_traj(rd[j], R0[j], ip[j], ρv[j], T) : ode_traj(rd[j], R0[j], ip[j], ρv[j], T)
        end
        # the trajectory functions give the expected counts that the likelihoods use
        j1 = 1
        μchk = map === :discrete ? mu_discrete(rd[j1], R0[j1], ip[j1], ρv[j1])[1] : mu_ode(rd[j1], R0[j1], ip[j1], ρv[j1])
        @assert maximum(abs.(μchk .- inc[:, j1])) < 1e-8 * max(1, maximum(μchk))
        nbad = count(j -> any(isnan, inc[:, j]), axes(inc, 2))
        keep = [j for j in axes(inc, 2) if !any(isnan, inc[:, j])]
        inc, prev, cid = inc[:, keep], prev[:, keep], cid[keep]
        peak = vec(maximum(prev, dims = 1)); cases = vec(sum(inc, dims = 1))
        bandline = "      $(size(inc, 2)) draws for the bands$(nbad > 0 ? " ($nbad dropped: ODE solve failed)" : ""): " *
                   "expected incidence peak $(q(vec(maximum(inc, dims=1)))) on step $(q(Float64.(vec(getindex.(argmax(inc, dims=1), 1))))) | " *
                   "number infectious peak $(q(peak)) | expected cases Στ·N $(q(cases))"
        if grid
            # grid posterior (no MCMC): pooled summaries over all 4,000 draws; s2_8_grid_poisson.jl's text output has the grid quantiles
            conv, rhat = true, NaN
            say("  $name: R0=$(q(g.R0)) | meanIP=$(q(g.mean_ip)) d | ρN=$(q(g.ρ .* N)) | " *
                (map === :ode ? "recorded mean interval=$(q(g.rec_ip)) d | " : "") *
                "P(r)=$(round.([mean(g.r .== r) for r in rsupport(map)], digits = 2)) | " *
                "$(length(g.R0)) independent draws from the numerical grid posterior (s2_8_grid_poisson.jl)")
            say(bandline)
            push!(res, (name = name, col = col, conv = conv, rhat = rhat, inc = bands(inc), prev = bands(prev)))
            continue
        end
        pars = filter(p -> p in (:R0, :mean_ip, :ρ), names(ch))
        s = summarystats(ch[pars])
        rhat = maximum(s[:, :rhat]); conv = rhat <= 1.01
        divc = Int.(vec(sum(Array(ch[:numerical_error]), dims = 1)))
        diag = "R̂≤$(round(rhat, digits=3)) ESS≥$(round(Int, minimum(s[:, :ess_bulk]))) div=$(sum(divc)) " *
               "(by chain $(divc)) | " * (t === nothing ? "chains loaded" : "$(round(Int, t)) s")
        if conv
            # converged: pooled posterior summaries over all draws
            rall = vec([sample_index(l) for l in returned(model, ch)])
            say("  $name: R0=$(q(vec(ch[:R0]))) | meanIP=$(q(vec(ch[:mean_ip]))) d | ρN=$(q(vec(ch[:ρ]) .* N)) | " *
                "P(r)=$(round.([mean(rall .== r) for r in rsupport(map)], digits = 2)) | $diag")
            say(bandline)
        else
            # not converged: the chains sit in different regions, so pooled summaries are not posterior summaries
            # (their weights depend on how many chains reached each region); report each chain on its own
            say("  $name: NOT CONVERGED, summaries by chain only | $diag")
            A = Dict(p => Array(ch[p]) for p in pars)
            rmat = [sample_index(l) for l in returned(model, ch)]
            for c in 1:nch
                say("      chain $c: R0=$(q(A[:R0][:, c])) | meanIP=$(q(A[:mean_ip][:, c])) d | ρN=$(q(A[:ρ][:, c] .* N))" *
                    " | r=$(q(Float64.(rmat[:, c]))) | " *
                    "mean log-joint $(round(mean(Array(ch[:logjoint])[:, c]), digits=1)) | number infectious peak $(q(peak[cid .== c])) | " *
                    "expected cases Στ·N $(q(cases[cid .== c]))")
            end
            nbad > 0 && say("      ($nbad of the trajectory draws dropped: ODE solve failed)")
        end
        chain_med(M) = [vec(median(M[:, cid .== c], dims = 2)) for c in 1:nch]
        push!(res, (name = name, col = col, conv = conv, rhat = rhat,
                    inc = conv ? bands(inc) : chain_med(inc), prev = conv ? bands(prev) : chain_med(prev)))
    end
    close(out)

    # ------------------------------------------------------------ figure: rows = new infections, number infectious; columns = models
    xs_inc = (1:T) .- 0.5                # step k covers (k − 1, k]
    xs_prev = 0:T
    ytop(x, conv) = conv ? maximum(x[3]) : maximum(maximum.(x))
    ymax_inc = 1.05 * maximum(vcat(th, inc_true, [ytop(r.inc, r.conv) for r in res]))
    ymax_prev = 1.05 * maximum(vcat(prev_true, prev_obs, [ytop(r.prev, r.conv) for r in res]))
    sty = (titlefontsize = 9, tickfontsize = 7, guidefontsize = 8, legendfontsize = 6, framestyle = :box,
           grid = :y, gridalpha = 0.15, foreground_color_legend = nothing, background_color_legend = nothing)
    # a converged fit is drawn as its posterior median and 95% CrI; a fit that did not converge (R̂ > 1.01) as the median
    # trajectory of each chain, with no pooled band
    function draw!(p, xs, r, x; label)
        if r.conv
            lo, md, hi = x
            plot!(p, xs, md; ribbon = (md .- lo, hi .- md), fillalpha = 0.25, color = r.col, lw = 2,
                  label = label ? "Posterior median, 95% CrI" : false)
        else
            for (c, m) in enumerate(x)
                plot!(p, xs, m; color = r.col, lw = 1.2, label = (label && c == 1) ? "Median of each chain" : false)
            end
        end
    end
    top, bot = [], []
    for (i, r) in enumerate(res)
        ttl = r.conv ? r.name : "$(r.name) (not converged, R̂ $(round(r.rhat, digits=2)))"
        # every top panel has a legend for its own model entry; the first also names the data and the truth
        p = bar(xs_inc, th; bar_width = 1.0, color = "#d6d5d0", lc = "#d6d5d0", lw = 0, label = i == 1 ? "Observed counts" : false,
                xlims = (0, T), ylims = (0, ymax_inc), title = ttl, ylabel = i == 1 ? "New infections per day" : "",
                legend = :topright, sty...)
        draw!(p, xs_inc, r, r.inc; label = true)
        plot!(p, xs_inc, inc_true; color = "#1f1e1c", lw = 1, label = i == 1 ? "True mean-field trajectory" : false)
        push!(top, p)
        p2 = plot(; xlims = (0, T), ylims = (0, ymax_prev), xlabel = "Day", ylabel = i == 1 ? "Number infectious" : "",
                  legend = i == 1 ? :topright : false, sty...)
        draw!(p2, xs_prev, r, r.prev; label = false)
        plot!(p2, xs_prev, prev_true; color = "#1f1e1c", lw = 1, label = false)
        scatter!(p2, xs_prev, prev_obs; ms = 2.2, msw = 0, color = "#8f8d87", label = "Observed (counted from the line list)")
        push!(bot, p2)
    end
    ρN = round(ρ_s * N_s, digits = 2)
    fig = plot(top..., bot..., layout = (2, length(res)), size = (1300, 560), left_margin = 4Plots.mm, bottom_margin = 3Plots.mm,
               plot_title = "N = $(fmt(N_s)) (incl. ρN = $(ρN == 1 ? 1 : ρN) initial infective$(ρN == 1 ? "" : "s")), K = $(fmt(K)) cases",
               plot_titlefontsize = 10, dpi = 200)
    savefig(fig, joinpath(FIGS, "s2_fig_trajectories_N$(N_s).png"))
    savefig(fig, joinpath(FIGS, "s2_fig_trajectories_N$(N_s).pdf"))
end
